object KoreanBank {
    /** 질문 | 보기에 크게 보일 말 | 정답 | 오답1,오답2,오답3 */
    private fun parse(s: String): List<Question> =
        s.trim().lines().map { it.trim() }.filter { it.isNotEmpty() }.map { line ->
            val p = line.split("|").map { it.trim() }
            val wrong = p[3].split(",").map { it.trim() }
            Question(prompt = p[0], big = p[1].ifEmpty { null }, choices = (wrong + p[2]).shuffled(),
                answer = p[2], explain = "정답: ${p[2]}")
        }

